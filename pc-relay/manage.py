"""manage.py — pc-relay 管理命令：Windows 注册表开机自启。

v2.0：拆为可导入函数——query_registry()/install()/uninstall() 返回结构化结果，
不打印不退出，供 admin.py（Web UI 开机自启开关）调用；CLI 走同一实现。

两种运行形态（自动探测）：
1. exe 模式（推荐）：服务 = 同目录（或 dist/pc-relay/）下 pc-relay.exe
   管理脚本自身可在任意 Python 下运行（WSL 或 Windows 均可，只需能调 reg.exe）。
2. venv 脚本模式（旧）：服务 = 本目录 .venv/bin/python main.py（需在 WSL 内运行）。

命令：
    python manage.py install-autostart    # 注册开机自启
    python manage.py uninstall-autostart  # 注销开机自启
    python manage.py status               # 查看注册状态

原理：Run 键 → wscript.exe（静默）→ deploy/autostart.vbs
      → exe 模式：直接启动 pc-relay.exe（读同目录 relay.db）
      → venv 模式：wsl.exe 在本项目目录启动 .venv/bin/python main.py。
"""

import os
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

RUN_KEY = r"HKCU\Software\Microsoft\Windows\CurrentVersion\Run"
VALUE_NAME = "MihuanNotifyRelay"
BASE = Path(__file__).resolve().parent

# exe 探测顺序：frozen 下以 sys.executable 目录为基准（__file__ 在 _internal/ 里）。
if getattr(sys, "frozen", False):
    _EXE_BASE = Path(sys.executable).resolve().parent
else:
    _EXE_BASE = BASE
EXE_CANDIDATES = [
    _EXE_BASE / "pc-relay.exe",
    _EXE_BASE / "dist" / "pc-relay" / "pc-relay.exe",
    _EXE_BASE / "_internal" / "pc-relay.exe",          # exe 被误放进 _internal/ 时兜底
    BASE / "pc-relay.exe",
    BASE / "dist" / "pc-relay" / "pc-relay.exe",
    BASE.parent / "build" / "pyinstaller" / "dist" / "pc-relay" / "pc-relay.exe",
]


@dataclass
class AutostartState:
    """query_registry() 的结构化结果。"""
    enabled: bool
    mode: str      # "exe" | "venv" | ""
    detail: str    # 给用户看的说明


def fail(msg: str) -> None:
    """CLI 模式：打印并退出。"""
    print(f"❌ {msg}")
    sys.exit(1)


def run_win(cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
    """调用 Windows 侧 exe（reg.exe 等）。"""
    try:
        return subprocess.run(cmd, capture_output=True, text=True, errors="replace", check=check)
    except FileNotFoundError:
        raise RuntimeError("找不到 reg.exe：请在 Windows 或 WSL（interop）内运行")
    except subprocess.CalledProcessError as e:
        print(f"  命令失败 rc={e.returncode}: {e.stderr or e.stdout}")
        raise


def wsl_to_win(path: Path) -> str:
    r = subprocess.run(["wslpath", "-w", str(path)], capture_output=True, text=True, check=True)
    return r.stdout.strip()


def win_to_wsl(path: Path) -> str:
    r = subprocess.run(["wslpath", "-u", str(path)], capture_output=True, text=True, check=True)
    return r.stdout.strip()


def find_exe() -> Path | None:
    for p in EXE_CANDIDATES:
        if p.is_file():
            return p
    return None


def check_env() -> tuple[Path, str]:
    """返回 (服务入口, 模式)。exe 优先；frozen 模式下服务就是自身 exe，无需探测。"""
    if getattr(sys, "frozen", False):
        return Path(sys.executable), "exe"
    exe = find_exe()
    if exe:
        return exe, "exe"
    if (BASE / ".venv/bin/python").exists():
        if not os.environ.get("WSL_DISTRO_NAME"):
            raise RuntimeError("未检测到 WSL_DISTRO_NAME：venv 模式须在 WSL 内运行（或先构建 pc-relay.exe 放到本目录）")
        return BASE / ".venv/bin/python", "venv"
    raise RuntimeError(f"未找到 pc-relay.exe（{BASE}/pc-relay.exe 或 build/pyinstaller/dist/pc-relay/）且无 .venv")


def vbs_content(exe_win: str) -> str:
    cmd = f'"{exe_win}"'
    # VBS 字符串转义：字面双引号写作 ""
    escaped = cmd.replace('"', '""')
    return (
        "' pc-relay autostart wrapper (generated by manage.py install-autostart)\n"
        'Set sh = CreateObject("WScript.Shell")\n'
        f'sh.Run "{escaped}", 0, False\n'
    )


def vbs_content_venv() -> str:
    distro = os.environ["WSL_DISTRO_NAME"]
    cmd = f'wsl.exe -d {distro} --cd {BASE} -- sh -c ".venv/bin/python main.py >> deploy/autostart.log 2>&1"'
    escaped = cmd.replace('"', '""')
    return (
        "' pc-relay autostart wrapper (generated by manage.py install-autostart)\n"
        'Set sh = CreateObject("WScript.Shell")\n'
        f'sh.Run "{escaped}", 0, False\n'
    )


# ---------------------------------------------------------------- 库函数（Web UI 调用）

def query_registry() -> AutostartState:
    """查询注册表 Run 键状态。reg.exe 不可用视为未启用。"""
    try:
        r = run_win(["reg.exe", "query", RUN_KEY, "/v", VALUE_NAME], check=False)
    except RuntimeError as e:
        return AutostartState(False, "", str(e))
    if r.returncode == 0:
        return AutostartState(True, "", f"Run\\{VALUE_NAME}；登录后自动后台启动，日志 deploy/autostart.log")
    return AutostartState(False, "", "未启用")


def _write_vbs(path: Path, content: str) -> None:
    """VBS 写盘：统一 LF 字节写入（沿用全项目「write_bytes + LF」约定）。"""
    path.write_bytes(content.replace("\r\n", "\n").encode("ascii"))


def install() -> dict:
    """注册开机自启。返回 {ok, mode, detail}，不打印不退出。"""
    try:
        entry, mode = check_env()
        deploy = BASE / "deploy"
        deploy.mkdir(exist_ok=True)
        vbs = deploy / "autostart.vbs"

        if mode == "exe":
            exe_win = wsl_to_win(entry) if os.environ.get("WSL_DISTRO_NAME") else str(entry)
            _write_vbs(vbs, vbs_content(exe_win))
        else:
            _write_vbs(vbs, vbs_content_venv())

        win_vbs = wsl_to_win(vbs) if os.environ.get("WSL_DISTRO_NAME") else str(vbs)
        run_win([
            "reg.exe", "add", RUN_KEY,
            "/v", VALUE_NAME, "/t", "REG_SZ",
            "/d", f'wscript.exe //B "{win_vbs}"', "/f",
        ])
        return {"ok": True, "mode": mode, "detail": f"{mode} 模式：{entry}；已写入注册表 Run 键"}
    except (RuntimeError, OSError, subprocess.CalledProcessError) as e:
        return {"ok": False, "mode": "", "detail": str(e)}


def uninstall() -> dict:
    """注销开机自启。返回 {ok, detail}。本就不存在也算 ok。"""
    try:
        r = run_win(["reg.exe", "delete", RUN_KEY, "/v", VALUE_NAME, "/f"], check=False)
        if r.returncode == 0:
            return {"ok": True, "detail": "已移除注册表自启项"}
        return {"ok": True, "detail": "自启项本就不存在"}
    except (RuntimeError, OSError) as e:
        return {"ok": False, "detail": str(e)}


def main() -> None:
    """CLI 包装：同一实现，打印结果。命令名保持旧版兼容。"""
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    try:
        if cmd == "install-autostart":
            r = install()
            if r["ok"]:
                print(f"✓ 开机自启已启用（{r['detail']}）")
            else:
                fail(r["detail"])
        elif cmd == "uninstall-autostart":
            r = uninstall()
            if r["ok"]:
                print(f"✓ {r['detail']}")
            else:
                fail(r["detail"])
        elif cmd == "status":
            st = query_registry()
            if st.enabled:
                print(f"● 开机自启：已启用（{st.detail}）")
            else:
                print(f"○ 开机自启：未启用（{st.detail}）")
        else:
            print(__doc__)
            sys.exit(1 if cmd else 0)
    except RuntimeError as e:
        fail(str(e))


if __name__ == "__main__":
    main()
